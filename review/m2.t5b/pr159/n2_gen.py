# Writes the specs of the survivors at 1a40bfc (nl_*.out), to run again at
# 11f02ef: n2_old_py.py, n2_old_sh.py (and the recorder's, split by hand into n2_old_rec_a.py and n2_old_rec_b.py). Run from this directory.
import re
def survivors(out):
    return {ln.split()[0] for ln in open(out) if ' SURVIVED' in ln}
def plants(spec):
    ns = {}
    exec(open(spec).read(), ns)
    return ns['PLANTS']
for dst, pairs in [('n2_old_py.py', [('nl_old_py.py', 'nl_old_py.out'), ('nl_new_py.py', 'nl_new_py.out')]),
                   ('n2_old_sh.py', [('nl_old_sh.py', 'nl_old_sh.out')]),
                   ('n2_old_rec.py', [('nl_r1.py', 'nl_r1.out'), ('nl_r2.py', 'nl_r2.out')])]:
    keep = []
    for spec, out in pairs:
        s = survivors(out)
        keep += [p for p in plants(spec) if p[0].split()[0] in s]
    with open(dst, 'w') as f:
        f.write('# The survivors at 1a40bfc, generated by n2_gen.py.\nPLANTS = [\n')
        for p in keep:
            f.write(' ' + repr(p) + ',\n')
        f.write(']\n')
    print(dst, len(keep), ' '.join(p[0].split()[0] for p in keep))
